// Builds CSS custom properties + a typed token list from src/tokens/primitives.tokens.json.
// Source of truth: Figma file "RHIA" → variable collection "Primitives" (modes Light / Dark).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/tokens/primitives.tokens.json');
const tokens = JSON.parse(readFileSync(src, 'utf8'));

const light = [];
const dark = [];
const list = [];

const quoteFamily = (f) => (/\s/.test(f) && !['system-ui', 'sans-serif'].includes(f) ? `'${f}'` : f);

function walk(node, trail) {
  if (node && typeof node === 'object' && '$value' in node) {
    const name = trail.join('-');
    const cssVar = `--${name}`;
    let value = node.$value;
    if (node.$type === 'fontFamily') value = value.map(quoteFamily).join(', ');
    light.push(`  ${cssVar}: ${value};`);
    const darkValue = node.$extensions?.['rhia.modes']?.dark;
    if (darkValue && darkValue !== value) dark.push(`  ${cssVar}: ${darkValue};`);
    list.push({
      name: trail.join('/'),
      cssVar,
      type: node.$type,
      value: String(value),
      dark: darkValue ?? null,
      description: node.$description ?? '',
    });
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    walk(child, [...trail, key]);
  }
}
walk(tokens, []);

const header = '/* GENERATED by scripts/build-tokens.mjs from src/tokens/primitives.tokens.json — do not edit by hand. */\n';
const css = `${header}
:root,
[data-theme='light'] {
  color-scheme: light;
${light.join('\n')}
}

[data-theme='dark'] {
  color-scheme: dark;
${dark.join('\n')}
}
`;
writeFileSync(path.join(root, 'src/tokens/primitives.css'), css);

const ts = `${header}
export type PrimitiveToken = {
  name: string;
  cssVar: string;
  type: string;
  value: string;
  dark: string | null;
  description: string;
};

export const primitives: PrimitiveToken[] = ${JSON.stringify(list, null, 2)};
`;
writeFileSync(path.join(root, 'src/tokens/primitives.ts'), ts);

console.log(`tokens: ${list.length} primitives → primitives.css (${dark.length} dark overrides) + primitives.ts`);


// ---------------------------------------------------------------------------
// Semantic colours (DRAFT) — src/tokens/semantic.tokens.json → semantic.css + semantic.ts
// Mirrors the Figma "Semantic" collection. CSS name: --color-<group>-<name>, e.g. --color-bg-surface.
const refToVar = (ref) => `--${ref.replace(/^\{|\}$/g, '').split('.').join('-')}`;
const semSrc = JSON.parse(readFileSync(path.join(root, 'src/tokens/semantic.tokens.json'), 'utf8'));
const semantic = [];
(function walkSem(node, trail) {
  if (node && typeof node === 'object' && '$value' in node) {
    const primitiveVar = refToVar(node.$value);
    if (!list.some((t) => t.cssVar === primitiveVar)) throw new Error(`semantic ${trail.join('/')}: unknown primitive ${node.$value}`);
    semantic.push({ name: trail.join('/'), cssVar: `--color-${trail.join('-')}`, alias: node.$value.replace(/^\{color\.|\}$/g, '').replace('.', '/'), primitiveVar, description: node.$description ?? '' });
    return;
  }
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walkSem(v, [...trail, k]);
})(semSrc, []);
const semHeader = '/* GENERATED by scripts/build-tokens.mjs from src/tokens/semantic.tokens.json — do not edit by hand. DRAFT: colours are suggestions. */\n';
writeFileSync(path.join(root, 'src/tokens/semantic.css'), `${semHeader}:root {\n${semantic.map((t) => `  ${t.cssVar}: var(${t.primitiveVar});`).join('\n')}\n}\n`);
writeFileSync(path.join(root, 'src/tokens/semantic.ts'), `${semHeader}
export type SemanticToken = { name: string; cssVar: string; alias: string; primitiveVar: string; description: string };
export const semantic: SemanticToken[] = ${JSON.stringify(semantic, null, 2)};
`);

// ---------------------------------------------------------------------------
// Text styles + effect styles — src/tokens/styles.tokens.json → styles.css + styles.ts
// Text: class .text-<group>-<name> (e.g. .text-heading-md). Effects: --shadow-xs, --focus-ring …
const stSrc = JSON.parse(readFileSync(path.join(root, 'src/tokens/styles.tokens.json'), 'utf8'));
const textStyles = Object.entries(stSrc.text).map(([name, t]) => {
  const v = t.$value;
  const decl = {
    'font-family': `var(${refToVar(v.fontFamily)})`,
    'font-weight': `var(${refToVar(v.fontWeight)})`,
    'font-size': `var(${refToVar(v.fontSize)})`,
    'line-height': `var(${refToVar(v.lineHeight)})`,
    'letter-spacing': v.letterSpacing,
    'text-transform': v.textTransform,
  };
  for (const val of Object.values(decl)) { const m = /var\((--[^)]+)\)/.exec(val); if (m && !list.some((t) => t.cssVar === m[1])) throw new Error(`text style ${name}: unknown ${m[1]}`); }
  const size = Number(/\d+$/.exec(v.fontSize.replace(/\}$/, ''))[0]);
  const lh = Number(/\d+$/.exec(v.lineHeight.replace(/\}$/, ''))[0]);
  return { name, className: `text-${name.replace('/', '-')}`, decl, size, lineHeight: lh, family: v.fontFamily.includes('mono') ? 'Geist Mono' : 'Geist', weight: v.fontWeight.split('.').pop().replace('}', ''), letterSpacing: v.letterSpacing, description: t.$description ?? '' };
});
const effects = Object.entries(stSrc.effect).map(([name, e]) => ({ name, cssVar: `--${name.replace('/', '-')}`, value: e.$value, description: e.$description ?? '' }));
const stHeader = '/* GENERATED by scripts/build-tokens.mjs from src/tokens/styles.tokens.json — do not edit by hand. */\n';
writeFileSync(path.join(root, 'src/tokens/styles.css'), `${stHeader}:root {\n${effects.map((e) => `  ${e.cssVar}: ${e.value};`).join('\n')}\n}\n\n${textStyles
  .map((t) => `.${t.className} {\n${Object.entries(t.decl).map(([k, val]) => `  ${k}: ${val};`).join('\n')}\n}`)
  .join('\n\n')}\n`);
writeFileSync(path.join(root, 'src/tokens/styles.ts'), `${stHeader}
export type TextStyle = { name: string; className: string; size: number; lineHeight: number; family: string; weight: string; letterSpacing: string; description: string };
export type EffectStyle = { name: string; cssVar: string; value: string; description: string };
export const textStyles: TextStyle[] = ${JSON.stringify(textStyles.map(({ decl, ...t }) => t), null, 2)};
export const effects: EffectStyle[] = ${JSON.stringify(effects, null, 2)};
`);
console.log(`tokens: ${semantic.length} semantic → semantic.css/ts · ${textStyles.length} text styles + ${effects.length} effects → styles.css/ts`);
